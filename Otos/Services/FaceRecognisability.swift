/// The direction unrecognisable faces share (ADR 0047).
///
/// AdaFace places a crop it cannot tell anyone by (a face blurred to nothing, turned upside
/// down, hidden by a costume or seen too close) near one common direction, whoever it shows.
/// Such faces are as alike to each other as to one person, so they chain into a person of
/// their own. `direction` is the mean embedding of 400 aligned crops shrunk to 8 px and
/// enlarged back, which keeps no identity: built by the research folder's
/// `tools/blurcrops` and `tools/facenorm`
/// (`docs/research/2026-11-13-unrecognisable-faces.md`). Regenerate it whenever the model
